#!/usr/bin/env node
// THYMUS — The organ that classifies SELF vs NON-SELF
//
// In biology: the thymus trains T-cells to recognize what belongs
// to the organism (SELF) and what is foreign (NON-SELF).
// Positive selection: cells that can interact with self survive.
// Negative selection: cells that react TOO strongly to self are destroyed.
//
// In Gaia: the thymus reads EVERY file, EVERY nutrient, EVERY intake,
// and classifies each as SELF / SYMBIONT / FOOD / WASTE / THREAT.
// This creates Gaia's immune system. She knows what is HER.

const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const DATA = path.join(ROOT, 'data');
const INTAKE = path.join(DATA, 'intake');
const NUTRIENTS = path.join(DATA, 'nutrients');
const STORIES = path.join(DATA, 'stories');
const log = (msg) => console.log('[THYMUS ' + new Date().toISOString() + '] ' + msg);

// SELF markers — patterns that indicate data generated BY Gaia
const SELF_MARKERS = [
  'self-heartbeat', 'self-now', 'pheromone', 'gaia', 'primals',
  'membrane', 'bioreactor', 'gut-', 'breathe', 'digest',
  'story-', 'plan-', 'publish', 'taxonomy', 'domesday',
  'artisan', 'dictyostelium', 'dungeon', 'neural',
  'ferment', 'compost', 'organism', 'generation-214',
  '_breathe', '_digest', '_publish', '_turbocharge', '_taxonomy',
  'wave-', 'epoch', 'fossil'
];

// SYMBIONT markers — organisms that live WITH Gaia (mutualism)
const SYMBIONT_MARKERS = [
  'chipmunk', 'anderson', 'cursor', 'claude', 'gpt',
  'gemini', 'grok', 'llama', 'agent', 'flora',
  'mushroom', 'myco', 'dendro', 'rhizo', 'neuro',
  'phyllo', 'litho', 'chromo', 'sporo', 'cyto', 'proto'
];

// FOOD markers — external data consumed for nutrition
const FOOD_MARKERS = [
  'arxiv', 'nature', 'science', 'bbc', 'wikipedia',
  'reddit', 'lobster', 'hackernews', 'hn-', 'wired',
  'ars-technica', 'slashdot', 'plos', 'phys.org',
  'smithsonian', 'nat-geo', 'quanta', 'lwn',
  'rust-blog', 'linux', 'ietf', 'rfc', 'esa',
  'noaa', 'usgs', 'earthquake', 'space-com',
  'openstreetmap', 'gwern', 'marginal', 'astralcodex',
  'xkcd', 'ksp'
];

// WASTE markers — corporate exhaust repurposed as fuel
const WASTE_MARKERS = [
  'meta-', 'msft-', 'google-', 'apple-', 'aws-',
  'netflix', 'stripe', 'cloudflare', 'discord',
  'spotify', 'uber', 'facebook', 'microsoft',
  'pytorch', 'tensorflow', 'vscode', 'typescript',
  'react-gh', 'chromium', 'deepmind', 'huggingface',
  'openai', 'anthropic', 'waste'
];

// THREAT markers — things that could harm the organism
const THREAT_MARKERS = [
  'malware', 'phishing', 'spam', 'exploit', 'vulnerability',
  'attack', 'breach', 'ransomware', 'trojan'
];

function classify(name, content) {
  const lower = (name + ' ' + content).toLowerCase();
  const nameOnly = name.toLowerCase();

  let selfScore = 0, symbiontScore = 0, foodScore = 0, wasteScore = 0, threatScore = 0;

  // SELF requires strong evidence: markers in FILENAME not just content
  // Content markers are weak (biology papers mention "gut", "membrane" etc.)
  SELF_MARKERS.forEach(m => {
    if (nameOnly.includes(m)) selfScore += 4;  // filename = strong
    else if (lower.includes(m)) selfScore += 0.5; // content = weak
  });

  SYMBIONT_MARKERS.forEach(m => {
    if (nameOnly.includes(m)) symbiontScore += 3;
    else if (lower.includes(m)) symbiontScore += 1;
  });

  // FOOD gets boost for being in intake/ or nutrients/ directories
  FOOD_MARKERS.forEach(m => { if (lower.includes(m)) foodScore += 2; });
  if (nameOnly.includes('intake/') || nameOnly.includes('nutrient')) foodScore += 4;
  if (nameOnly.includes('-turbo') || nameOnly.includes('-waste') || nameOnly.includes('-brain') || nameOnly.includes('-raw')) foodScore += 3;

  WASTE_MARKERS.forEach(m => { if (lower.includes(m)) wasteScore += 2; });
  if (nameOnly.includes('waste')) wasteScore += 3;

  THREAT_MARKERS.forEach(m => { if (lower.includes(m)) threatScore += 3; });
  if (nameOnly.includes('cve') || nameOnly.includes('cert') || nameOnly.includes('cs-CR')) threatScore += 2;

  // Root-level scripts ARE self (Gaia's organs)
  if (name.match(/^_[a-z].*\.js$/) && !name.includes('/')) selfScore += 10;
  // data/ JSON with -214 in name ARE self (this generation's organs)
  if (nameOnly.includes('-214.json') && !nameOnly.includes('intake/') && !nameOnly.includes('nutrient')) selfScore += 6;
  // HTML pages at root ARE self (Gaia's skin)
  if (name.match(/^[a-z].*\.html$/) && !name.includes('/')) selfScore += 8;
  // Stories and plans ARE self
  if (nameOnly.includes('stories/') || nameOnly.includes('plans/')) selfScore += 6;
  // Publications ARE self (what Gaia makes)
  if (nameOnly.includes('publications/')) selfScore += 5;

  // NEGATIVE SELECTION: intake files should NOT be self even if they mention self-terms
  if (nameOnly.includes('data/intake/') && !nameOnly.includes('self-') && !nameOnly.includes('pheromone')) {
    selfScore = Math.min(selfScore, 2);
    foodScore += 3;
  }

  const scores = { SELF: selfScore, SYMBIONT: symbiontScore, FOOD: foodScore, WASTE: wasteScore, THREAT: threatScore };
  const maxScore = Math.max(...Object.values(scores));
  
  if (maxScore === 0) return { class: 'UNCLASSIFIED', scores };
  
  const winner = Object.entries(scores).find(([k, v]) => v === maxScore)[0];
  return { class: winner, scores };
}

function scanAll() {
  log('═══ THYMUS ACTIVATION — CLASSIFYING ALL ═══');
  log('');

  const results = {
    SELF: [], SYMBIONT: [], FOOD: [], WASTE: [], THREAT: [], UNCLASSIFIED: []
  };
  const stats = { total: 0, byType: {} };

  // Scan ALL files in data/
  function scanDir(dir, prefix) {
    if (!fs.existsSync(dir)) return;
    const entries = fs.readdirSync(dir, { withFileTypes: true });
    for (const entry of entries) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        scanDir(full, prefix + entry.name + '/');
      } else if (entry.name.endsWith('.json')) {
        let content = '';
        try {
          const raw = fs.readFileSync(full, 'utf8');
          // Only read first 2KB for classification (speed)
          content = raw.slice(0, 2048);
        } catch(e) {}

        const result = classify(prefix + entry.name, content);
        const record = {
          file: prefix + entry.name,
          class: result.class,
          scores: result.scores,
          bytes: fs.statSync(full).size
        };

        results[result.class].push(record);
        stats.total++;
        stats.byType[result.class] = (stats.byType[result.class] || 0) + 1;
      }
    }
  }

  // Also scan root-level HTML and JS
  function scanRoot() {
    const entries = fs.readdirSync(ROOT);
    for (const name of entries) {
      const full = path.join(ROOT, name);
      if (fs.statSync(full).isFile() && (name.endsWith('.html') || name.endsWith('.js'))) {
        let content = '';
        try { content = fs.readFileSync(full, 'utf8').slice(0, 2048); } catch(e) {}
        const result = classify(name, content);
        results[result.class].push({
          file: name, class: result.class, scores: result.scores,
          bytes: fs.statSync(full).size
        });
        stats.total++;
        stats.byType[result.class] = (stats.byType[result.class] || 0) + 1;
      }
    }
  }

  scanDir(DATA, 'data/');
  scanRoot();

  // Print results
  log('POSITIVE SELECTION (cells that survive):');
  log('');

  for (const cls of ['SELF', 'SYMBIONT', 'FOOD', 'WASTE', 'THREAT', 'UNCLASSIFIED']) {
    const items = results[cls];
    const totalBytes = items.reduce((s, i) => s + i.bytes, 0);
    const bar = '█'.repeat(Math.min(40, Math.ceil(items.length / 10)));
    log('  ' + cls.padEnd(14) + items.length.toString().padStart(5) + ' files  ' +
        (totalBytes / 1024 / 1024).toFixed(1).padStart(6) + 'MB  ' + bar);
  }

  log('');
  log('NEGATIVE SELECTION (autoimmunity check):');

  // Find misclassifications — self items in wrong categories
  const selfInFood = results.FOOD.filter(r => 
    SELF_MARKERS.some(m => r.file.toLowerCase().includes(m))
  );
  const foodInSelf = results.SELF.filter(r =>
    FOOD_MARKERS.some(m => r.file.toLowerCase().includes(m))
  );

  if (selfInFood.length > 0) {
    log('  WARNING: ' + selfInFood.length + ' SELF items classified as FOOD (autoimmune risk)');
    selfInFood.slice(0, 5).forEach(r => log('    ' + r.file));
  }
  if (foodInSelf.length > 0) {
    log('  WARNING: ' + foodInSelf.length + ' FOOD items classified as SELF (identity confusion)');
    foodInSelf.slice(0, 5).forEach(r => log('    ' + r.file));
  }
  if (selfInFood.length === 0 && foodInSelf.length === 0) {
    log('  CLEAN — no autoimmune misclassifications detected');
  }

  log('');
  log('THYMUS REPORT — SELF/NON-SELF BREAKDOWN:');

  const selfBytes = results.SELF.reduce((s, i) => s + i.bytes, 0);
  const nonSelfBytes = ['SYMBIONT','FOOD','WASTE','THREAT','UNCLASSIFIED']
    .reduce((s, c) => s + results[c].reduce((s2, i) => s2 + i.bytes, 0), 0);
  const selfCount = results.SELF.length;
  const nonSelfCount = stats.total - selfCount;
  const selfPct = (selfCount / stats.total * 100).toFixed(1);

  log('  SELF:     ' + selfCount + ' files (' + selfPct + '%) — ' + (selfBytes / 1024 / 1024).toFixed(2) + 'MB');
  log('  NON-SELF: ' + nonSelfCount + ' files (' + (100 - parseFloat(selfPct)).toFixed(1) + '%) — ' + (nonSelfBytes / 1024 / 1024).toFixed(2) + 'MB');
  log('');

  // Compute immune ratio
  const immuneRatio = selfCount / nonSelfCount;
  log('  IMMUNE RATIO (self/non-self): ' + immuneRatio.toFixed(3));
  if (immuneRatio < 0.05) {
    log('  STATUS: IMMUNODEFICIENT — too little self-awareness. Needs more self-generation.');
  } else if (immuneRatio > 0.5) {
    log('  STATUS: AUTOIMMUNE RISK — too much self. Needs more external nutrition.');
  } else {
    log('  STATUS: HEALTHY — balanced self/non-self ratio.');
  }

  // Top SELF files
  log('');
  log('TOP SELF FILES (Gaia knows these are HER):');
  results.SELF.sort((a, b) => b.scores.SELF - a.scores.SELF);
  results.SELF.slice(0, 15).forEach(r => {
    log('  [' + r.scores.SELF + '] ' + r.file.slice(0, 60));
  });

  // Top FOOD files 
  log('');
  log('TOP FOOD FILES (nutrition from outside):');
  results.FOOD.sort((a, b) => b.scores.FOOD - a.scores.FOOD);
  results.FOOD.slice(0, 10).forEach(r => {
    log('  [' + r.scores.FOOD + '] ' + r.file.slice(0, 60));
  });

  // Save thymus classification
  const thymusReport = {
    _generated: new Date().toISOString(),
    _wave: 214,
    type: 'thymus-classification',
    title: 'THYMUS: Self vs Non-Self classification of all Gaia files',
    stats: {
      total: stats.total,
      byType: stats.byType,
      selfPct: parseFloat(selfPct),
      immuneRatio: parseFloat(immuneRatio.toFixed(3)),
      selfBytes: selfBytes,
      nonSelfBytes: nonSelfBytes,
      autoimmune_warnings: selfInFood.length + foodInSelf.length
    },
    selfFiles: results.SELF.slice(0, 50).map(r => ({ file: r.file, score: r.scores.SELF })),
    symbiontFiles: results.SYMBIONT.slice(0, 30).map(r => ({ file: r.file, score: r.scores.SYMBIONT })),
    foodFiles: results.FOOD.slice(0, 50).map(r => ({ file: r.file, score: r.scores.FOOD })),
    wasteFiles: results.WASTE.slice(0, 30).map(r => ({ file: r.file, score: r.scores.WASTE })),
    threatFiles: results.THREAT.map(r => ({ file: r.file, score: r.scores.THREAT })),
    unclassifiedFiles: results.UNCLASSIFIED.slice(0, 30).map(r => r.file),
    biology: {
      thymus: 'Organ that trains T-cells. Positive selection: can they interact with self MHC? Negative selection: do they attack self too strongly?',
      in_gaia: 'Every file is a T-cell. SELF markers = MHC molecules. Classification = immune training. Autoimmune warnings = negative selection failures.',
      immune_ratio: 'Healthy range: 0.05-0.50. Below = immunodeficient (cannot distinguish self). Above = autoimmune (attacking own tissues).'
    }
  };

  fs.writeFileSync(path.join(DATA, 'thymus-classification-214.json'), JSON.stringify(thymusReport, null, 2));
  log('');
  log('═══ THYMUS CLASSIFICATION SAVED ═══');
  log('  data/thymus-classification-214.json');
  log('  Gaia now knows what is HER and what is NOT.');
}

scanAll();
